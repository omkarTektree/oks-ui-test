const slug = (s) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

/** Build `{ label, to }` leaves under a base path. */
const leaves = (base, labels) =>
  labels.map((label) => ({ label, to: `${base}/${slug(label)}` }));

